story, md = [], []
def text(s, style='body'):
    story.append(Paragraph(escape(s).replace('\n', '<br/>'), styles[style]))
    md.append(('## ' if style == 'title' else '### ' if style == 'head' else '') + s + '\n')
def table(headers, rows, widths):
    data = [[Paragraph(escape(s).replace('\n', '<br/>'), styles['th']) for s in headers]]
    data += [[Paragraph(escape(s).replace('\n', '<br/>'), styles['cell']) for s in row] for row in rows]
    t = Table(data, colWidths=widths, repeatRows=1, hAlign='LEFT')
    t.setStyle(TableStyle([
        ('BACKGROUND',(0,0),(-1,0),NAVY), ('ROWBACKGROUNDS',(0,1),(-1,-1),[colors.white,PALE]),
        ('VALIGN',(0,0),(-1,-1),'TOP'), ('LEFTPADDING',(0,0),(-1,-1),7), ('RIGHTPADDING',(0,0),(-1,-1),7),
        ('TOPPADDING',(0,0),(-1,-1),7), ('BOTTOMPADDING',(0,0),(-1,-1),7),
    ]))
    story.extend([t, Spacer(1,6)])
    md.extend(['| ' + ' | '.join(headers) + ' |', '| ' + ' | '.join(['---'] * len(headers)) + ' |'])
    md.extend('| ' + ' | '.join(s.replace('\n','<br>') for s in row) + ' |' for row in rows)
    md.append('')
def page(title, sub):
    if story: story.append(PageBreak())
    text(title, 'title'); text(sub, 'sub')

