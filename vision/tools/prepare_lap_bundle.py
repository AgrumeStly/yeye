"""将L1现有模块合并为CanMV独立文件；不写板卡／main.py，不改冻结旧版本。

只去除本项目内部import，标准／MicroPython import保持原样；同一源文件哈希
写入manifest，便于把实板所运行副本与电脑检查对应起来。
"""
import argparse
import hashlib
import json
from pathlib import Path

p=argparse.ArgumentParser(); p.add_argument('--output',required=True)
p.add_argument('--grid-step',type=int,choices=(4,6),default=6); args=p.parse_args()
root=Path(__file__).resolve().parents[2]; output=Path(args.output); output.mkdir(parents=True,exist_ok=False)
names=('vision_protocol.py','lite_lap_route.py','lap_protocol.py','low_speed_lap_canmv.py')
parts=['# L1 development candidate; default IDLE; no automatic movement; generated by prepare_lap_bundle.py\n']
manifest={}
for name in names:
    source=root/'vision/src'/name; manifest[name]=hashlib.sha256(source.read_bytes()).hexdigest()
    text=source.read_text(encoding='utf-8')
    if name=='lite_lap_route.py':
        if text.count('GRID_STEP=4')!=1: raise RuntimeError('unexpected grid configuration')
        text=text.replace('GRID_STEP=4','GRID_STEP='+str(args.grid_step))
    lines=[line for line in text.splitlines() if not line.startswith(('from lite_lap_route import','from lap_protocol import','from vision_protocol import'))]
    parts.extend(['\n# BEGIN '+name+'\n','\n'.join(lines)+'\n'])
bundle=output/'low_speed_lap_canmv.py'; bundle.write_text(''.join(parts),encoding='utf-8')
compile(bundle.read_text(encoding='utf-8'),str(bundle),'exec')
manifest['bundle_sha256']=hashlib.sha256(bundle.read_bytes()).hexdigest()
manifest['grid_step']=args.grid_step
manifest['state']='development; IDLE; UART disabled; ALLOW_DRIVE false; not board/lap acceptance'
(output/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
print(bundle)
